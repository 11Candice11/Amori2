#!/usr/bin/env node
/**
 * Generates src/utils/cardImages.generated.ts from the files in images/cards.
 *
 * Metro only bundles images referenced by literal require('...') calls, so the
 * card list can't be built with a dynamic require at runtime. This script scans
 * the folder and writes the literal requires for every cardN.png it finds.
 *
 * Run automatically before start/ios/android. To run by hand: npm run cards
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const cardsDir = path.join(root, 'images', 'cards');
const outFile = path.join(root, 'src', 'utils', 'cardImages.generated.ts');

const numbers = fs
  .readdirSync(cardsDir)
  .map((file) => /^card(\d+)\.png$/.exec(file))
  .filter(Boolean)
  .map((match) => Number(match[1]))
  .sort((a, b) => a - b);

if (numbers.length === 0) {
  console.error(`No cardN.png files found in ${cardsDir}`);
  process.exit(1);
}

const lines = [
  '/* eslint-disable */',
  '// AUTO-GENERATED by scripts/generate-card-images.js. Do not edit by hand.',
  '// Re-run with: npm run cards',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  'export const CARD_IMAGES: Record<number, ImageSourcePropType> = {',
  ...numbers.map((n) => `  ${n}: require('../../images/cards/card${n}.png'),`),
  '};',
  '',
  'export const CARD_NUMBERS: number[] = [' + numbers.join(', ') + '];',
  '',
];

const next = lines.join('\n');
const prev = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
if (next !== prev) {
  fs.writeFileSync(outFile, next);
  console.log(`Generated ${path.relative(root, outFile)} (${numbers.length} cards)`);
}
